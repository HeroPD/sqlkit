export type MessageKey = keyof typeof enUS
type MessageValue = string | number
type MessageCatalog = Record<MessageKey, string>
const catalogs: Record<AppLocale, MessageCatalog> = { 'en-US': enUS }
let activeLocale: AppLocale = DEFAULT_LOCALE

export const getLocale = () => activeLocale

export function setLocale(locale: AppLocale) {
  activeLocale = locale
}

export function t(key: MessageKey, values: Record<string, MessageValue> = {}): string {
  return catalogs[activeLocale][key].replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match)
}

export const formatInteger = (value: number) => new Intl.NumberFormat(activeLocale).format(value)

/** Headline figures stay short enough for a sidebar tile: 1,284 → 1,284; 12,900 → 12.9K. */
export const formatCompact = (value: number) =>
  value < 10_000
    ? formatInteger(value)
    : new Intl.NumberFormat(activeLocale, { notation: 'compact', maximumFractionDigits: 1 }).format(value)

export const formatTime = (value: string | number | Date) =>
  new Intl.DateTimeFormat(activeLocale, { hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false })
    .format(new Date(value))

export const rowWord = (count: number) => t(count === 1 ? 'results.row' : 'results.rows')
